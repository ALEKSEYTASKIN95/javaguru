package org.javaguru.student_aleksey_taskin.lesson_5.level_4;

class SquareAndPerimeterCircleCalculator {

    public double perimeterCircleCalculate(double radius) {
        return 2 * Math.PI * radius;
    }

    public double squareCircleCalculate(double radius) {
        return Math.PI * radius * radius;
    }

}
